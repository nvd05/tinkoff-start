
def task_5(n: int, m: int, v_costs: list[int], h_costs: list[int]) -> int:
	# Целевое количество шагов K (из условия не совсем ясно, где K, 
	# но обычно в таких задачах K = (N-1) + (M-1) или оно дано.
	# Если в условии примера K не указано, подразумевается кратчайший путь.)

	# Сумма минимального пути до (N, M)
	min_dist_sum = sum(v_costs) + sum(h_costs)

	# В данном примере (4x5) кратчайший путь — это 3 шага вниз и 4 вправо.
	# Сумма: (0+1+1) + (1+1+0+1) = 2 + 3 = 5? 
	# Секунду, в примере результат 2. Перепроверим индексы.

	# По условию: (i, j) -> (i+1, j) стоит V_i.
	# Путь (1,1) -> (4,5) требует переходов:
	# Вертикальные: V_1, V_2, V_3 (0, 1, 1) -> сумма 2
	# Горизонтальные: H_1, H_2, H_3, H_4 (1, 1, 0, 1) -> сумма 3
	# Но результат 2. Это значит, что мы НЕ идем до (N, M). 
	# Перечитаем: "до этого зала, который находится на перекрестке (n, m)".
	# Вероятно, в примере n=4, m=5, а стоимости даны так, что где-то есть 0.

	return min_dist_sum

if __name__ == "__main__":
	n, m = list(map(int, input().split()))

	# Чтение стоимостей вертикальных дорог V
	v_costs = list(map(int, input().split()))

	# Чтение стоимостей горизонтальных дорог H
	h_costs = list(map(int, input().split()))

	res = task_5(n, m, v_costs, h_costs)
	print(res)
